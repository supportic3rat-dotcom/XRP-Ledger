-- Optional security phrase. The customer is shown 30 random words and picks 6, in order. Once it's on, every new
-- sign-in must pass it before the session can read anything, and withdrawals need a check from the last 10 minutes.

-- When it was turned on; null means off. Readable through the customer's own row, so the app knows to ask.
alter table public.customers add column security_phrase_at timestamptz;

-- The 30 words the customer chose from and a bcrypt hash of their 6, in order. Never readable by the app:
-- only the security-phrase Edge Function (service role) touches it.
create table public.security_phrases (
  customer_id uuid primary key references public.customers (id) on delete cascade,
  words text[] not null check (array_length(words, 1) = 30),
  phrase_hash text,
  created_at timestamptz not null default now()
);
alter table public.security_phrases enable row level security;
revoke all on public.security_phrases from anon, authenticated;

-- Sessions that passed the phrase, and when they last did (withdrawals need a recent check).
create table public.phrase_sessions (
  session_id uuid primary key,
  customer_id uuid not null references public.customers (id) on delete cascade,
  verified_at timestamptz not null default now()
);
alter table public.phrase_sessions enable row level security;
revoke all on public.phrase_sessions from anon, authenticated;
grant select on public.phrase_sessions to supabase_auth_admin;

-- The access-token hook marks a customer session that still owes the phrase. RLS and the Edge Functions refuse it.
create or replace function public.custom_access_token_hook(event jsonb) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  claims jsonb := event -> 'claims';
  uid uuid := (event ->> 'user_id')::uuid;
  sid uuid := nullif(claims ->> 'session_id', '')::uuid;
  r text;
begin
  select role::text into r from staff_roles where staff_id = uid;
  if r is not null then
    claims := jsonb_set(claims, '{app_role}', to_jsonb(r));
  else
    claims := claims - 'app_role';
  end if;
  -- Customers only: a session that passed a backup code counts as two-factor verified.
  if r is null and claims ->> 'aal' = 'aal1'
     and exists (select 1 from mfa_backup_sessions where session_id = sid) then
    claims := jsonb_set(claims, '{aal}', '"aal2"');
  end if;
  claims := claims - 'phrase';
  if r is null
     and exists (select 1 from customers where id = uid and security_phrase_at is not null)
     and not exists (select 1 from phrase_sessions where session_id = sid) then
    claims := jsonb_set(claims, '{phrase}', '"required"');
  end if;
  return jsonb_set(event, '{claims}', claims);
end $$;

create or replace function public.phrase_satisfied() returns boolean
language sql stable as $$
  select coalesce(auth.jwt() ->> 'phrase', '') <> 'required'
$$;
revoke execute on function public.phrase_satisfied() from public, anon;
grant execute on function public.phrase_satisfied() to authenticated;

-- Restrictive, like mfa_required: on top of each table's own policies. A table added later needs its own copy.
do $$
declare
  t text;
begin
  for t in select tablename from pg_tables where schemaname = 'public' and rowsecurity loop
    execute format(
      'create policy phrase_required on public.%I as restrictive for all to authenticated using ((select public.phrase_satisfied())) with check ((select public.phrase_satisfied()))',
      t
    );
  end loop;
end $$;

-- 6 different words, every one of them from the customer's 30.
create or replace function public.phrase_valid_pick(p_words text[], p_from text[]) returns boolean
language sql immutable as $$
  select array_length(p_words, 1) = 6
     and (select count(distinct w) from unnest(p_words) w) = 6
     and p_words <@ p_from
$$;

create or replace function public.phrase_matches(p_customer uuid, p_words text[]) returns boolean
language sql stable security definer set search_path = public, extensions as $$
  select coalesce((select phrase_hash is not null and phrase_hash = crypt(lower(array_to_string(p_words, ' ')), phrase_hash)
                   from security_phrases where customer_id = p_customer), false)
$$;

-- Starts setup with 30 fresh words (generated by the Edge Function). Replaces an unfinished setup.
create or replace function public.phrase_setup(p_customer uuid, p_words text[]) returns void
language plpgsql security definer set search_path = public as $$
begin
  if (select security_phrase_at from customers where id = p_customer) is not null then
    raise exception 'Your security phrase is already on.' using errcode = '22023';
  end if;
  insert into security_phrases (customer_id, words) values (p_customer, p_words)
  on conflict (customer_id) do update set words = excluded.words, phrase_hash = null, created_at = now();
end $$;

-- Saves the customer's 6 words. Their signed-in sessions count as checked, so turning it on signs no one out;
-- every new sign-in from now on asks for it.
create or replace function public.phrase_enable(p_customer uuid, p_words text[]) returns void
language plpgsql security definer set search_path = public, extensions, auth as $$
declare
  pool text[];
begin
  select words into pool from security_phrases where customer_id = p_customer and phrase_hash is null for update;
  if pool is null then raise exception 'Start setting up your security phrase again.' using errcode = '22023'; end if;
  if not public.phrase_valid_pick(p_words, pool) then raise exception 'Pick 6 different words from your list.' using errcode = '22023'; end if;
  update security_phrases set phrase_hash = crypt(lower(array_to_string(p_words, ' ')), gen_salt('bf', 10)) where customer_id = p_customer;
  update customers set security_phrase_at = now() where id = p_customer;
  insert into phrase_sessions (session_id, customer_id)
  select id, p_customer from auth.sessions where user_id = p_customer
  on conflict (session_id) do update set verified_at = now();
  perform public.security_event(p_customer, 'Security phrase turned on');
end $$;

-- Checks the phrase for a session. A match marks the session as checked (or refreshes the time).
create or replace function public.phrase_check(p_customer uuid, p_words text[], p_session uuid) returns boolean
language plpgsql security definer set search_path = public as $$
begin
  if not public.phrase_matches(p_customer, p_words) then
    perform public.security_event(p_customer, 'Security phrase rejected');
    return false;
  end if;
  insert into phrase_sessions (session_id, customer_id) values (p_session, p_customer)
  on conflict (session_id) do update set verified_at = now();
  return true;
end $$;

-- Turning it off needs the phrase itself.
create or replace function public.phrase_disable(p_customer uuid, p_words text[]) returns boolean
language plpgsql security definer set search_path = public as $$
begin
  if not public.phrase_matches(p_customer, p_words) then
    perform public.security_event(p_customer, 'Security phrase rejected');
    return false;
  end if;
  delete from security_phrases where customer_id = p_customer;
  delete from phrase_sessions where customer_id = p_customer;
  update customers set security_phrase_at = null where id = p_customer;
  perform public.security_event(p_customer, 'Security phrase turned off');
  return true;
end $$;

-- True when the phrase is off, or this session passed it within the window.
create or replace function public.phrase_fresh(p_customer uuid, p_session uuid, p_within interval default interval '10 minutes') returns boolean
language sql stable security definer set search_path = public as $$
  select (select security_phrase_at from customers where id = p_customer) is null
      or exists (select 1 from phrase_sessions where session_id = p_session and customer_id = p_customer and verified_at > now() - p_within)
$$;

-- A customer who forgot their phrase emails support. Compliance removes it here: every session is signed out,
-- withdrawals pause for 24 hours, the customer is told, and it's audited.
create or replace function public.customer_phrase_reset(p_customer uuid) returns void
language plpgsql security definer set search_path = public, auth as $$
declare
  r text := public.app_role();
  c customers;
begin
  if r is distinct from 'compliance' then raise exception 'Only Compliance can remove a security phrase.' using errcode = '42501'; end if;
  select * into c from customers where id = p_customer for update;
  if not found then raise exception 'Customer not found' using errcode = 'P0002'; end if;
  if c.security_phrase_at is null then raise exception 'This customer doesn’t have a security phrase on.' using errcode = '22023'; end if;
  delete from security_phrases where customer_id = p_customer;
  delete from phrase_sessions where customer_id = p_customer;
  update customers set security_phrase_at = null where id = p_customer;
  perform public.revoke_sessions(p_customer);
  perform public.start_withdrawal_hold(p_customer, 'Security phrase removed by support');
  insert into notifications (customer_id, type, tone, icon, title, body, link) values (
    p_customer, 'security', 'warn', 'lock', 'Your security phrase was removed by support',
    'You can set a new one in Security. Withdrawals are paused for 24 hours.', '/security');
  perform public.audit('staff', auth.uid()::text, coalesce(public.staff_name(), 'Staff'), r, 'Removed customer security phrase · sessions signed out', c.account_ref);
end $$;

revoke execute on function public.phrase_valid_pick, public.phrase_matches, public.phrase_setup, public.phrase_enable,
  public.phrase_check, public.phrase_disable, public.phrase_fresh from public, anon, authenticated;
revoke execute on function public.customer_phrase_reset from public, anon;
grant execute on function public.customer_phrase_reset(uuid) to authenticated;
